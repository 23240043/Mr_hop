    <h3 style="color: var(--color-primary); margin-top: 30px;">El garaje — 2015</h3>
    <p>Tres amigos, una olla, un sueño. Carlos, Memo y Andrés empezaron a cocinar cerveza casera los fines de semana en el garaje de la casa de uno de ellos. Lo que arrancó como un pasatiempo terminó siendo una obsesión: probar cada estilo, leer cada libro, viajar a cada festival cervecero que podían pagar.</p>

    <h3 style="color: var(--color-primary); margin-top: 30px;">La primera taproom — 2018</h3>
    <p>Tras tres años perfeccionando recetas y participando en concursos locales (ganando algunos), abrimos las puertas de la primera taproom de Mr. Hop. Un local pequeño, ocho grifos, una pizarra con tizas de colores y muchas ganas. La comunidad cervecera respondió.</p>

    <h3 style="color: var(--color-primary); margin-top: 30px;">Hoy — La cervecería completa</h3>
    <p>En 2024 dimos el salto: ampliamos a 20 grifos rotativos, montamos cocina propia para maridajes serios y construimos esta plataforma digital para que pedir tu IPA favorita sea tan fácil como escanear un QR. La fábrica sigue creciendo, pero la filosofía no cambia: lúpulos premium, fermentación lenta y mucho amor en cada barril.</p>

